import { copyFile, mkdir, writeFile } from 'node:fs/promises';
import { pinyin } from 'pinyin-pro';

const chars = [];
const initials = [];
for (let codePoint = 0x4e00; codePoint <= 0x9fff; codePoint++) {
  const char = String.fromCodePoint(codePoint);
  const first = pinyin(char, { toneType: 'none', pattern: 'first', type: 'array' })[0];
  if (/^[a-z]$/.test(first || '')) {
    chars.push(char);
    initials.push(first);
  }
}
const output = `// Generated by scripts/build-pinyin-map.mjs from pinyin-pro 3.29.5 (MIT).
// Maps common CJK characters to their primary pinyin initial for local search.
export const pinyinChars = ${JSON.stringify(chars.join(''))};
export const pinyinInitials = ${JSON.stringify(initials.join(''))};
`;
await mkdir(new URL('../dist/vendor/', import.meta.url), { recursive: true });
await writeFile(new URL('../dist/vendor/pinyin-initials.js', import.meta.url), output);
await copyFile(
  new URL('../node_modules/pinyin-pro/LICENSE', import.meta.url),
  new URL('../dist/vendor/pinyin-pro.LICENSE.txt', import.meta.url),
);
console.log(`Wrote ${chars.length} pinyin initials to dist/vendor/pinyin-initials.js`);
